<script lang="ts">
  import { onMount } from 'svelte';
  import { getCurrentWindow } from '@tauri-apps/api/window';
  import { Card, Label, Pill, StatusDot } from '@hyprkvm/hypr-ui';
  import { actions, asError, backend, onPhonePairing } from '../../lib/backend.svelte';
  import type { PairingCode } from '../../lib/types';

  type Phase = 'opening' | 'waiting' | 'paired' | 'expired' | 'failed';

  let phase = $state<Phase>('opening');
  let code = $state<PairingCode | null>(null);
  let left = $state(0);
  let pairedName = $state('');
  let failure = $state('');
  let copied = $state(false);
  let deadline = 0;

  async function open() {
    phase = 'opening';
    failure = '';
    try {
      code = await actions.startPhonePairing();
      deadline = Date.now() + code.expires_in_secs * 1000;
      left = code.expires_in_secs;
      phase = 'waiting';
    } catch (error) {
      failure = asError(error).message;
      phase = 'failed';
    }
  }

  onMount(() => {
    const unlisten = onPhonePairing((update) => {
      if (phase !== 'waiting') return;
      if (update.state === 'paired') {
        pairedName = update.name;
        phase = 'paired';
      } else {
        phase = 'expired';
      }
    });
    const tick = setInterval(() => {
      if (phase !== 'waiting') return;
      left = Math.max(0, Math.round((deadline - Date.now()) / 1000));
      if (left === 0) phase = 'expired';
    }, 250);
    return () => {
      clearInterval(tick);
      unlisten.then((stop) => stop());
    };
  });

  // The code lives in the backend connection; losing it withdraws the code.
  $effect(() => {
    if (backend.connection.status !== 'connected' && phase === 'waiting') {
      failure = 'Lost the backend, so the code was withdrawn.';
      phase = 'failed';
      code = null;
    }
  });

  // Start once the backend is reachable; retry if it was still starting.
  $effect(() => {
    if (backend.connection.status === 'connected' && phase === 'opening' && !code) open();
  });

  function close() {
    // The window going away cancels the code (see main.rs); closing never pairs.
    getCurrentWindow().close();
  }

  async function copyLink() {
    if (!code) return;
    await navigator.clipboard.writeText(code.uri);
    copied = true;
    setTimeout(() => (copied = false), 1500);
  }

  function keydown(event: KeyboardEvent) {
    if (event.key === 'Escape') close();
  }

  const clock = $derived(`${Math.floor(left / 60)}:${String(left % 60).padStart(2, '0')}`);
</script>

<svelte:window onkeydown={keydown} />

<div class="pairbody" data-tauri-drag-region>
  <div class="phead" data-tauri-drag-region>
    <span class="label" style="color:var(--white)">{phase === 'paired' ? 'Phone added' : 'Scan with HyprMobile'}</span>
    <button class="ib small" aria-label="Close" onclick={close}>✕</button>
  </div>

  {#if phase === 'paired'}
    <Card dots class="donecard">
      <span class="dot live big"></span>
      <span class="display" style="font-size:44px">Added</span>
    </Card>
    <p class="center">{pairedName}</p>
    <p class="center dim">Clipboard and notifications follow your Home settings.</p>
    <div class="btnrow"><Pill onclick={close}>Done</Pill></div>
  {:else}
    <div class="countrow">
      <Label>Add a phone</Label>
      <span class="display count" class:gone={phase !== 'waiting'}>{phase === 'waiting' ? clock : '0:00'}</span>
    </div>
    <div class="qrcard" class:gone={phase !== 'waiting'}>
      {#if code}
        <!-- Generated by the app from the backend's pairing link. -->
        {@html code.qr_svg}
      {:else}
        <div class="qrblank"></div>
      {/if}
    </div>
    <div class="status">
      {#if phase === 'waiting'}
        <StatusDot state="blink" /><span>Waiting for the phone…</span>
      {:else if phase === 'opening'}
        <StatusDot state="blink" /><span>
          {backend.connection.status === 'connected' ? 'Making a code…' : 'Waiting for the backend…'}
        </span>
      {:else if phase === 'expired'}
        <StatusDot /><span class="dim">The code expired.</span>
      {:else}
        <StatusDot /><span class="dim">{failure}</span>
      {/if}
    </div>
    <Label class="small">{phase === 'waiting' ? 'The phone must be on the same network' : 'Show a new code to try again'}</Label>
    <div class="btnrow">
      {#if phase === 'waiting'}
        <Pill variant="ghost" onclick={copyLink}>{copied ? 'Copied' : 'Copy link'}</Pill>
        <Pill variant="ghost" onclick={close}>Cancel</Pill>
      {:else}
        <Pill variant="ghost" onclick={close}>Close</Pill>
        <Pill disabled={backend.connection.status !== 'connected' || phase === 'opening'} onclick={open}>Show a new code</Pill>
      {/if}
    </div>
  {/if}
</div>

